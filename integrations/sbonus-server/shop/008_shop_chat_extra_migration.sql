-- ============================================================================
-- Интернет-магазин Smart Centr: товары со склада, которых нет на сайте, — для чата.
-- Только новая таблица; существующие не затрагиваются.
--
-- 1С присылает их вместе с каталогом: цена уже посчитана в 1С (цена сайта или
-- себестоимость + наценка владельца). Себестоимость сюда не приходит никогда.
-- На сайте эти товары не показываются: только чат знает о них и может продать.
-- ============================================================================

CREATE TABLE IF NOT EXISTS shop_chat_extra (
    id          INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    data        JSONB       NOT NULL,            -- {"items": [...]}
    items_count INTEGER     NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP   NOT NULL DEFAULT NOW()
);
