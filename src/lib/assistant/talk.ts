function count(low: string, words: RegExp): number {
  return (low.match(words) ?? []).length
}

export function detectLang(text: string, fallback: TalkLang): TalkLang {
  const low = text.toLowerCase()

  if (/[ўғқҳ]/.test(low)) return 'uz'
  if (/[ңөү]/.test(low)) return 'ky'

  // Конца слова не проверяем: в узбекском к корню липнут окончания
  // («yetkaz» → «yetkazib», «bor» → «bormi»), и \b в конце всё бы испортил.
  const uzWords = /\b(assalom|salom|qancha|qanaqa|qanday|narx|bormi|kerak|olmoq|olaman|olsam|yetkaz|rahmat|raqam|do.?kon|muzlatgich|changyutgich|kir mashina|nechta|necha|bo.?ladi|arzon|kafolat|to.?lo|sotib|buyurtma|nasiya|oy qoldi|xayr|pul|qachan|keladi|tushunmadim|bilmadim|ayting|aytasiz|menga|sizda|uchun|qayerga|qaerga|tashla|tashe|bering|beraman|qilsam|mumkin|yaxshi|kechir)/i
  const kyWords = /\b(salam|kanday|baasy|barby|kerek|jetkir|rakmat|kancha|dukon|kaerde|arzan|kepildik)/i

  if (uzWords.test(low)) return 'uz'
  if (kyWords.test(low)) return 'ky'

  /**
   * Целая фраза латиницей без кыргызских слов — почти наверняка узбекская:
   * так пишут в Араванском районе. Одно слово не в счёт, иначе «Samsung» или
   * «LG» от русского покупателя переводили бы разговор на узбекский.
   */
  const latinWords = low.match(/[a-z']{2,}/g) ?? []
  if (latinWords.length >= 3 && !/[а-яё]/i.test(low)) return 'uz'

  // Узбекская кириллица без ў/ғ/қ/ҳ — так пишут с обычной русской клавиатуры:
  // «яхшимисиз», «меники канча колди», «расмини ташолесими». Считаем, каких
  // слов больше — узбекских или кыргызских: «канча» есть в обоих языках, и
  // одно слово ничего не решает.
  const uzScore = count(low, UZ_CYR)
  const kyScore = count(low, KY_CYR)
  if (uzScore > kyScore) return 'uz'
  if (kyScore > uzScore) return 'ky'

  // Кыргызская и узбекская кириллица без особых букв. Слова редкие, в русском
  // тексте не встречаются, поэтому ищем их просто как куски строки: граница
  // слова \b кириллицу не видит и здесь бесполезна.
  if (/(канча|канчадан|баасы|барбы|керек|жеткир|рахмат|саламатсыз|дүкөн|кайда|арзан|кепилдик|заказым|бар бы)/i.test(low)) {
    return 'ky'
  }
  if (/(қанча|нарх|керак|раҳмат|дўкон|бормий|бўлиб|неча ой)/i.test(low)) return 'uz'



  // Кириллица без узбекских и кыргызских букв — считаем русским.
  if (/[а-я]/.test(low)) return 'ru'
  return fallback
}

/**
 * Узбекский латиницей → кириллицей обычными русскими буквами (без ў, ғ, қ, ҳ —
 * так здесь пишут все, латиницу многие не читают). Для готовых фраз запасного
 * режима, статусов заказа и месяцев; ответы модели — сразу кириллицей.
 *
 * Слова с цифрами, ЗАГЛАВНЫЕ коды моделей и уже кириллические — не трогаем.
 */
const PAIRS: [RegExp, string][] = [
  [/o[\u02bb\u2018\u2019']/g, 'у'],
  [/g[\u02bb\u2018\u2019']/g, 'г'],
  [/sh/g, 'ш'], [/ch/g, 'ч'], [/ya/g, 'я'], [/yo/g, 'ё'], [/yu/g, 'ю'], [/ye/g, 'е'],
  [/[\u02bb\u2018\u2019']/g, 'ъ'],
  [/^e/, 'э'],
]
const LETTERS: Record<string, string> = {
  a: 'а', b: 'б', d: 'д', e: 'е', f: 'ф', g: 'г', h: 'х', i: 'и', j: 'ж', k: 'к', l: 'л', m: 'м', n: 'н',
  o: 'о', p: 'п', q: 'к', r: 'р', s: 'с', t: 'т', u: 'у', v: 'в', x: 'х', y: 'й', z: 'з', c: 'ц', w: 'в',
}

export function uzCyrillic(text: string): string {
  return text.replace(/[A-Za-z0-9\u02bb\u2018\u2019']+/g, (word) => {
    if (/\d/.test(word) || (word.length > 1 && word === word.toUpperCase())) return word
    const capital = word[0] === word[0].toUpperCase()
    let out = word.toLowerCase()
    for (const [from, to] of PAIRS) out = out.replace(from, to)
    out = out.replace(/[a-z]/g, (ch) => LETTERS[ch] ?? ch)
    return capital ? out.charAt(0).toUpperCase() + out.slice(1) : out
  })
}

/**
 * Имя из телефона владельца бывает «.», «А», «Клиент розничная», «шмотка».
 * Одна буква или без букв — не имя; служебные пометки — тоже.
 */
export function cleanName(name?: string): string | undefined {
  const value = (name ?? '').trim()
  const letters = value.replace(/[^\p{L}]/gu, '')
  if (letters.length < 2) return undefined
  if (/(клиент|розничн|шмотка|уста|мастер|водител|шопур|такси|поставщ|магазин|дукон|дүкөн)/i.test(value)) return undefined
  return value.slice(0, 40)
}
