/**
 * Язык разговора.
 *
 * Сайт бывает только русским и кыргызским, а покупатель пишет ещё и
 * по-узбекски: магазин стоит в Араванском районе, где по-узбекски говорят
 * каждый день, и пишут его и латиницей, и кириллицей.
 *
 * Язык определяем сами, а не поручаем это языковой модели. Быстрая дешёвая
 * модель на кыргызский вопрос отвечала по-русски; когда язык назван ей прямо
 * («отвечай по-кыргызски»), она не ошибается.
 */

import type { Lang } from '@/lib/i18n/config'

export type TalkLang = 'ru' | 'ky' | 'uz'

export const LANG_NAME: Record<TalkLang, string> = {
  ru: 'русский',
  ky: 'кыргызский',
  uz: 'узбекский',
}

/**
 * На каком языке пишет покупатель.
 *
 * Считаем приметы, а не угадываем: узбекскую кириллицу (ў, ғ, қ, ҳ) и
 * кыргызскую (ң, ө, ү) не спутать, а латиницу узнаём по частым словам.
 * Ничего не нашли — отвечаем на языке сайта.
 */
/** Узбекские слова кириллицей, которых нет в кыргызском. Целые слова. */
const UZ_CYR =
  /(?<![\p{L}])(яхшимисиз|яхшимисан|яхши|меники|сеники|бизга|менга|сизга|битта|иккита|керегиди|керак|керакми|канака|кандайдир|тавсия|киласиз|киламан|киламиз|килсам|расм|расми|расмини|ташланг|ташолесими|ташолас|ташла|бердиз|берасиз|берасизми|колди|колган|колдими|олсам|оламан|оламиз|олмокчи|нархи|нарх|бормикан|борми|шуни|буни|нима|нимага|качон|узим|узимиз|мумкинми|мумкин|айтинг|хозир|чикади|тушади|тушмади|ойлик|ойга|бўлади|булади|буладими|йук|йўк|ха|хоп|яна|хам|хамма|учун|билан|кейин|олдин|аввал|дейсиз|дедингиз|курсам|курмокчи|ишлайди|ишлайдими|йахши|йахшимисиз|чарчаме|чарчамай|ишлайапсими|ишлаяпсизми|уко|соглигиз|соглигингиз|тинчмисиз|тузукмисиз|маслахат|маслахатлашиб|килиб|килай|олай|олайлик|уйлаб|уйлаймиз|кураман|курайлик|айтаман|ёзаман|богланаман|бераман|хозирча|керакмас|тулов|туловни|толов|толовни|каерга|каерда|кайерга|кайерда|киламиз|киламан|килса|булса|бошка|бошкалар|бизнинг|сизнинг|манзил|манзили|манзилингиз|рахмат сизга|катта рахмат)(?![\p{L}])/giu
