const SOFT = (text: string) =>
  text
    .toLowerCase()
    .replace(/ё/g, 'е').replace(/ө/g, 'о').replace(/[үў]/g, 'у').replace(/қ/g, 'к').replace(/ғ/g, 'г').replace(/ҳ/g, 'х')
    // o'sh, oʻzgan, o’sh — апостроф в узбекской латинице
    .replace(/['ʻʼ’`]/g, '')
const place = (s: string) => new RegExp(`(?<![\\p{L}])${s.replace(/-/g, '[\\s-]?')}\\p{L}{0,5}(?![\\p{L}])`, 'iu')
// Короткие слова — только с падежными окончаниями: «до пяти любых букв» поймало бы «ошибка», а «оша» по-узбекски — «тот».
// «Уш» — узбекское «Ўш» (ў → у). «Манас» — ещё и имя, и улица в каждом городе: только «Манаска», «Манас району».
const SHORT = [
  /(?<![\p{L}])(?:ош(?:ко|то|тон|тун|тан|тин|тогу|тагы|до|дон|да|дан|га|ка|ке|е|у|ом|ск\p{L}{0,3})?|из\s+оша)(?![\p{L}])/iu,
  /(?<![\p{L}])(?:уш(?:га|да|дан|лик|ликман)|osh(?:ga|da|dan|lik)?)(?![\p{L}])/iu,
  /(?<![\p{L}])(?:манас(?:\s*(?:район|шаар|айыл|шахар|город)\p{L}*|(?:ка|та|тан|га|да|дан|ке|е)(?:мын|мин|быз|сыз|ман|миз)?)|manas(?:ga|da|dan|ka|ta|tan))(?![\p{L}])/iu,
]
const FREE = FREE_DELIVERY_SPELLINGS.map(place)
const PAID = PAID_SPELLINGS.map(place)

/** Покупатель назвал место, куда доставка бесплатная, и ни одного другого. Только тогда «привезём бесплатно» — правда. */
export function mentionsFreeDelivery(text: string): boolean {
  const soft = SOFT(text)
  if (PAID.some((re) => re.test(soft))) return false
  return SHORT.some((re) => re.test(soft)) || FREE.some((re) => re.test(soft))
}

