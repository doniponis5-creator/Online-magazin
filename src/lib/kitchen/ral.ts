const BY_CODE = new Map(RAL.map((c) => [c.code, c]))

/** Цвет RAL по коду «7016»; нет такого — undefined. */
export function ralColor(code: string): RalColor | undefined {
  return BY_CODE.get(code)
}

/**
 * Код RAL из того, что ввёл человек: «7016», «RAL 7016», «ral7016», «RAL-7016», с пробелами → «7016».
 * Не четыре цифры или такого кода в RAL Classic нет — null.
 */
export function parseRal(input: string): string | null {
  const s = input.toLowerCase().replace(/[\s\-_.]+/g, '').replace(/^ral/, '')
  return /^\d{4}$/.test(s) && BY_CODE.has(s) ? s : null
}
