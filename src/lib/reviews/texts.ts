export function reviewTexts(lang: Lang): ReviewTexts {
  return lang === 'ky' ? ky : ru
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''))
}

/**
 * Дата отзыва. По-кыргызски — цифрами: не каждый браузер знает кыргызские
 * названия месяцев и подставляет русские («26 сентября»).
 */
export function reviewDate(value: string, lang: Lang): string {
  const date = new Date(value)
  if (lang === 'ky') return date.toLocaleDateString('ru-RU', { day: '2-digit', month: '2-digit', year: 'numeric' })
  return date.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long', year: 'numeric' })
}
