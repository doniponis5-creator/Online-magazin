function plural(n: number, one: string, few: string, many: string): string {
  const a = n % 10
  const b = n % 100
  if (a === 1 && b !== 11) return one
  if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return few
  return many
}

export function galleryTexts(lang: Lang): GalleryTexts {
  return lang === 'ky' ? ky : ru
}

/**
 * Ответ API → понятная фраза; незнакомый код — «не получилось сохранить».
 * У too-many фраза уточняется по reason: больше 5 фото, 300 комментариев, часто.
 */
export function errorText(lang: Lang, error: unknown, reason?: unknown): string {
  const t = galleryTexts(lang)
  if (error === 'too-many' && typeof reason === 'string' && reason in t.tooMany) return t.tooMany[reason as TooManyReason]
  return typeof error === 'string' && error in t.errors ? t.errors[error as ApiError] : t.errors.save
}

