/**
 * Факты о товарах, которых нет в 1С, — со слов владельца или с сайта производителя.
 *
 * Консультант видит их рядом с характеристиками товара. Раньше на «до скольки лет?»
 * и «какой размер?» модель отвечала наугад («12 жашка чейин», «85×60×60 см» у плиты,
 * у которой в 1С размеров нет). Здесь — только проверенное: владелец сказал или
 * производитель пишет. Появились те же сведения в 1С — строку отсюда можно убрать.
 *
 * Ключ — id товара (cb-…), значение — строки, как их сказал бы продавец.
 */
export const PRODUCT_FACTS: Record<string, string[]> = {
  // Электро Эндуро WN-A10 — владелец, 01.10.2026
  'cb-00002545': [
    'возраст: для детей 8–10 лет',
    'заряда хватает на 3–4 часа катания',
    'где кататься: дома, во дворе, на улице махалли; в горы и по камням НЕ рекомендуем',
  ],
}

/** Строка «от владельца: …» для каталога консультанта; нет фактов — пусто. */
export function productFacts(id: string): string {
  const facts = PRODUCT_FACTS[id]
  return facts && facts.length > 0 ? `проверено (владелец / производитель): ${facts.join('; ')}` : ''
}
