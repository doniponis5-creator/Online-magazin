/** Тексты конструктора кухни на русском и кыргызском. */

function goods(n: number): string {
  const a = n % 10
  const b = n % 100
  if (a === 1 && b !== 11) return 'товар'
  if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return 'товара'
  return 'товаров'
}

